function cleanRoutePath(pathname) {
  const rawPath = String(pathname || "/").split("?")[0].split("#")[0] || "/";
  return rawPath.replace(/\/+$/, "") || "/";
}

export function normalizeRoutePath(pathname) {
  const path = cleanRoutePath(pathname);
  if (path === "/") {
    return "/";
  }
  if (ROUTES.some((route) => route.path === path)) {
    return path;
  }
  if (path.startsWith("/reliability/work-orders/") && path !== "/reliability/work-orders") {
    return "/reliability/work-orders/detail";
  }
  if (path.startsWith("/research-lab/") && !ROUTES.some((route) => route.path === path)) {
    return "/research-lab";
  }
  return LEGACY_ROUTE_ALIASES[path] || path;
}

function contractFromRoute(route, requestedPath = route?.path) {
  const override = OPERATOR_SHELL_ROUTE_NAV_OVERRIDES[route.path] || {};
  const routeId = override.route_id || route.route_id || route.id;
  return {
    ...route,
    route_id: routeId,
    id: route.id || routeId,
    path: route.path,
    requested_path: requestedPath || route.path,
    canonical_path: override.canonical_path || route.path,
    nav_item_id: override.nav_item_id || route.nav_item_id || route.id,
    parent_nav_item_id: override.parent_nav_item_id || route.parent_nav_item_id || null,
    workspace_id: override.workspace_id || route.workspace_id || "legacy",
    title: route.title || route.label || routeId,
  };
}


