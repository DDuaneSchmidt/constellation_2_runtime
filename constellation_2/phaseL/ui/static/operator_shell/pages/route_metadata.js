export const OPERATOR_SHELL_ROUTE_REGISTRY = ROUTES.map((route) => contractFromRoute(route));

export function operatorShellRouteContractForPath(pathname) {
  const normalizedPath = normalizeRoutePath(pathname);
  const route = ROUTES.find((candidate) => candidate.path === normalizedPath);
  if (!route) {
    return {
      ...NOT_FOUND_ROUTE,
      requested_path: cleanRoutePath(pathname),
      title: NOT_FOUND_ROUTE.title,
    };
  }
  return contractFromRoute(route, cleanRoutePath(pathname));
}

export function activeNavSelectionForPath(pathname) {
  const contract = operatorShellRouteContractForPath(pathname);
  return {
    route_id: contract.route_id,
    path: contract.path,
    nav_item_id: contract.nav_item_id,
    parent_nav_item_id: contract.parent_nav_item_id,
    workspace_id: contract.workspace_id,
    title: contract.title,
    is_unknown_route: contract.route_id === NOT_FOUND_ROUTE.route_id,
  };
}

export function routeShouldPreserveDayQuery(pathname) {
  const workspaceId = activeNavSelectionForPath(pathname).workspace_id;
  return ["cio", "command_center", "positions", "history", "performance", "research", "engineering"].includes(workspaceId);
}

