def test_operator_command_registry_forbids_execution_order_and_capital_actions() -> None:
    registry = operator_command_registry_v1()

    for command in ["BUY", "SELL", "EXECUTE", "SUBMIT_ORDER", "ROUTE_ORDER", "ALLOCATE_CAPITAL", "MUTATE_SLEEVE"]:
        assert command in registry["forbidden_commands"]
        assert command not in registry["allowed_commands"]
    assert "RECORD_MANUAL_EXTERNAL_CAPTURE" in registry["allowed_commands"]
    assert registry["broker_execution_allowed"] is False


def test_every_open_task_has_primary_command_and_stable_sort() -> None:
    projection = operator_task_projection_v1(_cockpit())
    open_tasks = [task for task in projection["tasks"] if task["resolution_state"] == "open"]

    assert open_tasks
    assert all(task["primary_command"] for task in open_tasks)
    assert all(task["owner_type"] == "operator" for task in open_tasks)
    assert all(task["ui_resolvable"] is True for task in open_tasks)
    assert all(task["workflow_route"] for task in open_tasks)
    assert all(task["direct_action"] not in {"Review", "Open", "Investigate", "Resolve"} for task in open_tasks)
    assert [task["task_id"] for task in projection["tasks"]] == sorted([task["task_id"] for task in projection["tasks"]])


