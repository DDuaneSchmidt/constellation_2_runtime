def test_manual_capture_snapshots_decision_support_fingerprint(tmp_path: Path) -> None:
    cockpit = _cockpit()
    cockpit["top_candidates"] = [_supported_candidate()]
    decision = active_opportunity_projection_v1(cockpit)["candidates"][0]["candidate_decision_projection"]
    result = execute_operator_command_v1(
        truth_root=tmp_path,
        repo_root=REPO_ROOT,
        day_utc="2026-05-19",
        cockpit_payload=cockpit,
        request_payload={
            "command_type": "RECORD_MANUAL_EXTERNAL_CAPTURE",
            "target_id": "cand-spy-long",
            "source_projection_fingerprint": decision["projection_fingerprint"],
            "actor": "David",
            "payload": {
                "quantity": 1,
                "manually_captured": True,
                "capture_timestamp": "2026-05-19T15:50:00Z",
                "unsupported_evidence_acknowledgement": True,
            },
        },
    )

    events = read_operator_events_v1(truth_root=tmp_path, day_utc="2026-05-19")
    assert result["ok"] is True
    assert len(events) == 1
    assert events[0]["event_type"] == "MANUAL_EXTERNAL_CAPTURE_RECORDED"
    assert events[0]["decision_support_snapshot"]["projection_fingerprint"] == decision["projection_fingerprint"]
    assert events[0]["manual_capture_snapshot"]["decision_support_fingerprint"] == decision["projection_fingerprint"]
    assert events[0]["manual_capture_snapshot"]["symbol"] == "SPY"
    assert events[0]["manual_capture_snapshot"]["quantity"] == 1
    assert events[0]["manual_capture_snapshot"]["acknowledgement_text_accepted"] == "I understand Aegis evidence is incomplete and Aegis did not execute this trade."
    assert events[0]["operator_statement"] == "Aegis did not execute this trade."


