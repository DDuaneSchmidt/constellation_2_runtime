def test_runtime_truth_and_vix_blocker_are_diagnostics_not_tasks() -> None:
    cockpit = _cockpit_with_vix_blocker()
    tasks = operator_task_projection_v1(cockpit)["tasks"]
    diagnostics = system_diagnostic_projection_v1(cockpit)["diagnostics"]

    assert all("runtime" not in str(task.get("title", "")).lower() for task in tasks)
    assert all(task.get("task_type") != "blocker_resolution_if_operator_actionable" for task in tasks)
    assert any(row["diagnostic_type"] == "runtime_truth_partial" for row in diagnostics)
    assert any(row["diagnostic_type"] == "missing_market_data" and row["issue"].startswith("VIX") for row in diagnostics)
    assert any(row["diagnostic_type"] == "blocked_sleeve" and row["operator_impact"].find("VIX") >= 0 for row in diagnostics)
    assert all(row["ownership_classification"] == "system_diagnostic" for row in diagnostics)
    vix = next(row for row in diagnostics if row["diagnostic_type"] == "missing_market_data")
    assert vix["required_canonical_symbol"] == "VIX"
    assert vix["symbol_status"] == "missing"
    assert vix["affected_sleeves"] == ["C2_VOL_INCOME_DEFINED_RISK_V1"]
    assert "provider_attempts" in vix


