def _diagnostic_types(snapshot: dict[str, object]) -> set[str]:
    projection = snapshot.get("system_diagnostics_projection") or {}
    return {str(row.get("diagnostic_type") or "") for row in projection.get("diagnostics", [])}


def _snapshot_without_diagnostics(snapshot: dict[str, object]) -> dict[str, object]:
    mutated = copy.deepcopy(snapshot)
    for key in ("system_diagnostics_projection", "system_diagnostic_projection"):
        projection = dict(mutated.get(key) or {})
        projection["diagnostics"] = []
        projection["critical_count"] = 0
        projection["warning_count"] = 0
        mutated[key] = projection
    return mutated


def test_snapshot_builder_gives_every_projection_the_same_snapshot_id() -> None:
    snapshot = build_operator_state_snapshot_v1(_cockpit_with_vix_blocker())
    expected = snapshot["snapshot_id"]

    for key in [
        "operator_today_projection",
        "passive_health_projection",
        "operator_tasks_projection",
        "system_diagnostics_projection",
        "what_changed_projection",
        "opportunities_projection",
        "eod_outcome_projection",
    ]:
        assert snapshot[key]["snapshot_id"] == expected
        assert snapshot[key]["source_fingerprint"] == snapshot["source_fingerprint"]


def test_health_facts_drive_today_health_and_diagnostics() -> None:
    snapshot = build_operator_state_snapshot_v1(_cockpit_with_vix_blocker())

    assert snapshot["health_facts"]["blocked_sleeves_count"] == 1
    assert snapshot["health_facts"]["data_warnings_count"] == 1
    assert snapshot["operator_today_projection"]["blocked_sleeves_count"] == 1
    assert snapshot["operator_today_projection"]["data_warnings_count"] == 1
    assert any(row["health_id"] == "health:blocked_sleeves" and row["value"] == 1 for row in snapshot["passive_health_projection"]["health"])
    assert {"blocked_sleeve", "missing_market_data", "runtime_truth_unavailable"} <= _diagnostic_types(snapshot)
    assert snapshot["validation_result"]["status"] == "PASS"


def test_validator_rejects_blocked_sleeves_with_empty_diagnostics() -> None:
    snapshot = _snapshot_without_diagnostics(build_operator_state_snapshot_v1(_cockpit_with_vix_blocker()))
