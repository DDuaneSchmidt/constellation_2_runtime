def test_manual_capture_eligibility_is_unchanged_by_snapshot_builder() -> None:
    direct_projection = active_opportunity_projection_v1(_cockpit())
    snapshot = build_operator_state_snapshot_v1(_cockpit())
    snapshot_projection = snapshot["opportunities_projection"]

    assert direct_projection["candidate_count"] == 1
    assert snapshot_projection["candidate_count"] == direct_projection["candidate_count"]
    assert snapshot_projection["candidates"][0]["manual_capture_eligible"] is True
    assert "RECORD_MANUAL_EXTERNAL_CAPTURE" in snapshot_projection["candidates"][0]["candidate_decision_projection"]["allowed_commands"]
    assert snapshot["broker_execution_allowed"] is False
    assert snapshot["autonomous_execution_allowed"] is False
    assert snapshot["order_routing_allowed"] is False


def test_selected_exposure_and_suppressed_watchlist_flow_from_operator_snapshot() -> None:
    snapshot = build_operator_state_snapshot_v1(_cockpit_with_operator_snapshot())

    active = snapshot["active_opportunity_projection"]
    today = snapshot["operator_today_projection"]

    assert active["candidate_count"] == 0
    assert active["selected_candidate_count"] == 1
    assert active["suppressed_count"] == 41
    assert active["blocked_conversion_count"] == 1
    assert active["manual_capture_candidate"]["symbol"] == "AMT"
    assert active["suppressed_candidate_watchlist"]["candidates"][0]["symbol"] == "QQQ"
    assert today["selected_candidate_count"] == 1
    assert today["suppressed_count"] == 41
    assert today["blocked_conversion_count"] == 1
    assert snapshot["health_facts"]["advisory_status"] == "Partial"
    assert "stale_market_data" in _diagnostic_types(snapshot)


